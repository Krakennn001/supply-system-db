ALTER TABLE Details
	ALTER COLUMN Name SET NOT NULL,
	ADD CHECK(Price > 0),
	ALTER COLUMN Price SET NOT NULL,
	ADD CHECK(Weight > 0);

ALTER TABLE Suppliers
	ALTER COLUMN Address SET DEFAULT('неизвестен'),
	ALTER COLUMN Address SET NOT NULL,
	ALTER COLUMN City SET NOT NULL,
	ADD CHECK(Rating > 0 AND Rating < 11),
	ALTER COLUMN Name SET NOT NULL,
	ADD UNIQUE(Name, City);

ALTER TABLE Projects
	ALTER COLUMN Address SET NOT NULL,
	ALTER COLUMN City SET NOT NULL,
	ALTER COLUMN Name SET NOT NULL,
	ADD CHECK(SupplySum >= 0),
	ALTER COLUMN SupplySum SET DEFAULT 0;

ALTER TABLE Supply
	ADD CHECK(DetailsAmount > 0),
	ALTER COLUMN SupplyCost SET DEFAULT 0,
	ADD CHECK(SupplyCost >= 0),
	ADD FOREIGN KEY(DetailID) REFERENCES Details (ID) ON DELETE SET NULL ON UPDATE CASCADE,
	ADD FOREIGN KEY (SupplierID) REFERENCES Suppliers (ID) ON DELETE SET NULL ON UPDATE CASCADE,
	ADD FOREIGN KEY (ProjectID) REFERENCES Projects (ID) ON DELETE SET NULL ON UPDATE CASCADE;